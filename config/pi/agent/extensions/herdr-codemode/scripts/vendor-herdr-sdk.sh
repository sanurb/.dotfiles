#!/usr/bin/env bash
# Rebuilds @herdr/sdk from a local checkout and copies its bundle and wire contract into vendor/.
# Usage: scripts/vendor-herdr-sdk.sh <path-to-herdr-sdk-checkout>
set -euo pipefail

sdk_dir="${1:?Usage: scripts/vendor-herdr-sdk.sh <path-to-herdr-sdk-checkout>}"
sdk_dir="$(cd "$sdk_dir" && pwd)"
extension_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
vendor_dir="$extension_dir/vendor/herdr-sdk"

(cd "$sdk_dir" && pnpm run build)

mkdir -p "$vendor_dir"
cp "$sdk_dir/LICENSE" "$vendor_dir/LICENSE"
cp "$sdk_dir/dist/index.mjs" "$vendor_dir/index.mjs"
cp "$sdk_dir/dist/index.d.mts" "$vendor_dir/index.d.mts"
cp "$sdk_dir/schema/herdr-api.schema.json" "$vendor_dir/herdr-api.schema.json"
# Wire method → accepted result types; the test fixture server answers every method from it.
node --input-type=module - "$sdk_dir" > "$vendor_dir/wire-result-types.json" <<'NODE'
import { pathToFileURL } from "node:url";
import { join } from "node:path";
const { wireResultTypesByMethod } = await import(pathToFileURL(join(process.argv[2], "src/generated/wire-method-map.ts")).href);
process.stdout.write(JSON.stringify(wireResultTypesByMethod, null, 2) + '\n');
NODE

commit="$(git -C "$sdk_dir" rev-parse HEAD)"
dirty="$(git -C "$sdk_dir" status --porcelain | head -1)"
version="$(node -p 'JSON.parse(require("node:fs").readFileSync(process.argv[1], "utf8")).version' "$sdk_dir/package.json")"
cat > "$vendor_dir/VENDORED.md" <<EOF
# Vendored @herdr/sdk

Generated by \`scripts/vendor-herdr-sdk.sh\`; do not edit these files by hand.

- Version: $version
- Source commit: $commit${dirty:+ (working tree had uncommitted changes)}
- Runtime dependencies (pinned in ../../package.json): effect, @effect/platform-node-shared, ajv
EOF

echo "Vendored @herdr/sdk $version ($commit) into $vendor_dir"
